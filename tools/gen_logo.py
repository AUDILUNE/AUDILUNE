"""AUDILUNE single-screen 240x240 boot splash generator:
Combines assets/audilune_logo.jpg (crescent moon) with smooth 3D-embossed
white AUDILUNE + v1.0 typography on a pure black 240x240 canvas.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LOGO_JPG = ROOT / "assets" / "audilune_logo.jpg"

SPLASH_W, SPLASH_H = 240, 240
BLACK = (0, 0, 0)
WHITE = (255, 255, 255)
TURQUOISE = (0, 197, 205)  # #00C5CD


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def find_font(size, bold=True):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/System/Library/Fonts/Helvetica.ttc",
    ]
    for path in candidates:
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def draw_embossed_centered(draw, y, text, font, face_col, hi_col, sh_col):
    bbox = draw.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0]
    x = (SPLASH_W - tw) // 2 - bbox[0]
    # Deep bottom-right shadow
    draw.text((x + 2, y + 2), text, font=font, fill=sh_col)
    draw.text((x + 1, y + 1), text, font=font, fill=sh_col)
    # Subtle top-left bevel highlight
    draw.text((x - 1, y - 1), text, font=font, fill=hi_col)
    # Crisp main white face
    draw.text((x, y), text, font=font, fill=face_col)


def load_audilune_splash():
    canvas = Image.new("RGB", (SPLASH_W, SPLASH_H), BLACK)

    # 1) Place crescent moon logo in upper-center (136x136 max)
    if LOGO_JPG.exists():
        im = Image.open(LOGO_JPG).convert("RGB")
        im.thumbnail((136, 136), Image.LANCZOS)
        ox = (SPLASH_W - im.width) // 2
        oy = 16 + (136 - im.height) // 2
        canvas.paste(im, (ox, oy))

    # 2) Render smooth 3D-embossed "AUDILUNE" + "v1.0" underneath
    draw = ImageDraw.Draw(canvas)
    font_title = find_font(28, bold=True)
    font_ver = find_font(14, bold=False)

    draw_embossed_centered(
        draw,
        y=164,
        text="AUDILUNE",
        font=font_title,
        face_col=(255, 255, 255),
        hi_col=(180, 195, 210),
        sh_col=(55, 65, 80),
    )
    draw_embossed_centered(
        draw,
        y=202,
        text="v1.0",
        font=font_ver,
        face_col=(190, 200, 215),
        hi_col=(110, 120, 135),
        sh_col=(35, 40, 50),
    )
    return canvas


def splash_header(path):
    im = load_audilune_splash()

    cols = [BLACK]
    for f in (0.15, 0.30, 0.45, 0.60, 0.75, 0.90, 1.0):
        cols.append(tuple(round(v * f) for v in TURQUOISE))
    for f in (0.20, 0.40, 0.60, 0.80, 1.0):
        cols.append(tuple(round(v * f) for v in WHITE))
    for t in (0.25, 0.50, 0.75):
        cols.append(tuple(round(TURQUOISE[i] * (1 - t) + WHITE[i] * t) for i in range(3)))

    src = im.tobytes()
    px = []
    cache = {}
    for i in range(0, len(src), 3):
        p = (src[i], src[i + 1], src[i + 2])
        if p not in cache:
            if p[0] < 18 and p[1] < 18 and p[2] < 18:
                cache[p] = 0
            else:
                cache[p] = min(range(16), key=lambda k: sum((p[j] - cols[k][j]) ** 2 for j in range(3)))
        px.append(cache[p])

    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j

    L = [
        "/* generated by tools/gen_logo.py: AUDILUNE 240x240 unified boot splash */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define SLOOP_SPLASH_W {SPLASH_W}",
        f"#define SLOOP_SPLASH_H {SPLASH_H}",
        "static const uint16_t SLOOP_SPLASH_PAL[16] = {" + ", ".join(f"0x{rgb565(c):04X}" for c in cols) + "};",
        f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{",
    ]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")
    print(f"logo: AUDILUNE splash {SPLASH_W}x{SPLASH_H}, {len(rle)} B RLE -> {path}")


def assets(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    im = load_audilune_splash()
    im.resize((SPLASH_W * 2, SPLASH_H * 2), Image.NEAREST).save(out / "sloop-splash.png")
    print(f"logo: assets in {out}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--assets":
        assets(sys.argv[2])
    elif len(sys.argv) == 2:
        splash_header(sys.argv[1])
    else:
        sys.exit(__doc__)
