"""AUDILUNE boot splash logo generator: loads assets/audilune_logo.jpg, centers it on a
pure black 200x200 canvas, quantizes to 16 colours, and writes RLE RGB565 C header data.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LOGO_JPG = ROOT / "assets" / "audilune_logo.jpg"

SPLASH_W, SPLASH_H = 200, 200
BLACK = (0, 0, 0)
WHITE = (255, 255, 255)
TURQUOISE = (0, 197, 205)  # #00C5CD


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def load_audilune_logo(W, H):
    im = Image.open(LOGO_JPG).convert("RGB")
    im.thumbnail((W, H), Image.LANCZOS)
    canvas = Image.new("RGB", (W, H), BLACK)
    ox = (W - im.width) // 2
    oy = (H - im.height) // 2
    canvas.paste(im, (ox, oy))
    return canvas


def splash_header(path):
    im = load_audilune_logo(SPLASH_W, SPLASH_H)

    cols = [BLACK]
    for f in (0.15, 0.30, 0.45, 0.60, 0.75, 0.90, 1.0):
        cols.append(tuple(round(v * f) for v in TURQUOISE))
    for f in (0.20, 0.40, 0.60, 0.80, 1.0):
        cols.append(tuple(round(v * f) for v in WHITE))
    for t in (0.25, 0.50, 0.75):
        cols.append(tuple(round(TURQUOISE[i] * (1 - t) + WHITE[i] * t) for i in range(3)))

    src = im.tobytes()
    px = []
    cache = {}
    for i in range(0, len(src), 3):
        p = (src[i], src[i + 1], src[i + 2])
        if p not in cache:
            if p[0] < 18 and p[1] < 18 and p[2] < 18:
                cache[p] = 0
            else:
                cache[p] = min(range(16), key=lambda k: sum((p[j] - cols[k][j]) ** 2 for j in range(3)))
        px.append(cache[p])

    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j

    L = [
        "/* generated by tools/gen_logo.py: AUDILUNE crescent moon boot splash */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define SLOOP_SPLASH_W {SPLASH_W}",
        f"#define SLOOP_SPLASH_H {SPLASH_H}",
        "static const uint16_t SLOOP_SPLASH_PAL[16] = {" + ", ".join(f"0x{rgb565(c):04X}" for c in cols) + "};",
        f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{",
    ]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")
    print(f"logo: AUDILUNE splash {SPLASH_W}x{SPLASH_H}, {len(rle)} B RLE -> {path}")


def assets(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    im = load_audilune_logo(SPLASH_W, SPLASH_H)
    im.resize((SPLASH_W * 2, SPLASH_H * 2), Image.NEAREST).save(out / "sloop-splash.png")
    print(f"logo: assets in {out}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--assets":
        assets(sys.argv[2])
    elif len(sys.argv) == 2:
        splash_header(sys.argv[1])
    else:
        sys.exit(__doc__)
